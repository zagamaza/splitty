// ShareOfMinorStep — каноническое деление в копейках с ШАГОМ: каждая доля
// кратна step, а их сумма в точности равна sum.
//
// ⚠️ Шаг нужен тусе без копеек. Там доля обязана быть кратна единице валюты:
// иначе человеку показывают долю, которую он не может ни заплатить, ни увидеть,
// а сумма долей на экране расходится с итогом. Расход 1000 ¥ на троих без шага
// дал бы 333,34 + 333,33 + 333,33 — три числа, которых у иены не существует.
//
// Если сам итог не кратен шагу (старый дробный расход в тусе, где копейки
// выключили), шаг игнорируется: кратными долями несовместимый итог не набрать,
// а сойтись с ним обязательно.
func ShareOfMinorStep(sum int64, n, i int, step int64) int64 {
	if step <= 1 || sum%step != 0 {
		return shareOfMinor(sum, n, i)
	}
	return shareOfMinor(sum/step, n, i) * step
}

// shareOfMinor — то же каноническое правило деления, что и ShareOf, но в
// копейках. Отдельная функция, а не приведение к int: единица денег в модели
// одна, и смешивать типы на границе значит однажды перепутать их.
func shareOfMinor(sum int64, n, i int) int64 {
	share := sum / int64(n)
	rem := sum % int64(n)
	if rem < 0 {
		if int64(i) < -rem {
			share--
		}
		return share
	}
	if int64(i) < rem {
		share++
	}
	return share
}
