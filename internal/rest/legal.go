package rest

import (
	"html/template"
	"net/http"
)

// Публичные страницы: политика конфиденциальности и удаление аккаунта.
//
// Оба магазина требуют ссылку, доступную БЕЗ входа в приложение: ревьюер
// открывает её в браузере, и «страница за авторизацией» — повод для отказа.
// До этих страниц у Splitty не было ни одной: обязательного текста про
// распознавание голоса и чеков (материал уходит на сервер и в стороннюю
// модель) человеку негде было прочитать.

// legalPage — общая обёртка страницы: тёмная тема, читаемая ширина, без
// внешних ресурсов (шрифты и скрипты со стороны на такой странице неуместны).
var legalPage = template.Must(template.New("legal").Parse(`<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{{.Title}} — Splitty</title>
<style>
:root { color-scheme: light dark; }
body {
  margin: 0 auto; padding: 32px 20px 64px; max-width: 42rem;
  font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  color: #101828; background: #F6F7F9;
}
@media (prefers-color-scheme: dark) { body { color: #F2F4F7; background: #0C0F13; } }
h1 { font-size: 28px; line-height: 1.25; margin: 0 0 8px; }
h2 { font-size: 19px; margin: 32px 0 8px; }
p, li { margin: 8px 0; }
.updated { color: #667085; font-size: 14px; margin: 0 0 24px; }
</style>
</head>
<body>
<h1>{{.Title}}</h1>
<p class="updated">Обновлено: {{.Updated}}</p>
{{.Body}}
</body>
</html>`))

type legalData struct {
	Title   string
	Updated string
	Body    template.HTML
}

// legalUpdated — дата последнего изменения текстов. Меняется руками вместе с
// содержимым: автоматическая дата «сегодня» врала бы о том, что текст свежий.
const legalUpdated = "13 августа 2026"

// handlePrivacyPolicy GET /privacy — политика конфиденциальности.
func (s *Server) handlePrivacyPolicy(w http.ResponseWriter, _ *http.Request) {
	writeLegal(w, legalData{
		Title:   "Политика конфиденциальности",
		Updated: legalUpdated,
		Body: `
<h2>Какие данные мы храним</h2>
<p>Имя и способ входа (Telegram, Google, Apple или электронная почта), группы,
их участники, расходы и погашения: суммы, описания, даты и то, между кем расход
делится. Всё это нужно, чтобы считать, кто кому сколько должен, — без этих
данных приложение не выполняет свою работу.</p>
<p>Если вы разрешили уведомления, мы храним токен устройства, чтобы их
доставлять.</p>

<h2>Голос и фото чека</h2>
<p>Когда вы диктуете расход или снимаете чек, запись или снимок уходят на сервер
Splitty и передаются в стороннюю модель распознавания, которая превращает их в
черновик расхода. Мы не используем эти материалы ни для чего другого и не
храним их дольше, чем нужно для распознавания.</p>
<p>Само распознавание на устройстве не делается: без отправки на сервер эта
функция не работает. Ею можно не пользоваться — расход всегда можно внести
руками.</p>

<h2>Отчёты о падениях</h2>
<p>Если приложение падает, мы получаем технический отчёт: стек ошибки, модель
устройства и версию системы. Он не связан с вашим аккаунтом и не содержит ваших
расходов — только то, что нужно, чтобы починить поломку.</p>

<h2>Кому мы передаём данные</h2>
<p>Стороннему сервису распознавания — голос и изображения чеков, как описано
выше. Сервису доставки уведомлений — текст уведомления и токен устройства.
Больше никому: мы не продаём данные и не передаём их рекламным сетям.</p>

<h2>Сколько мы храним</h2>
<p>Данные группы живут, пока существует сама группа. Когда вы удаляете аккаунт,
профиль удаляется, а имя во всех расходах заменяется на «Удалённый
пользователь»: сами расходы остаются у остальных участников, потому что это
их общий счёт, а не только ваш.</p>

<h2>Как удалить данные</h2>
<p>Удалить аккаунт можно прямо в приложении: «Профиль» → «Удалить аккаунт».
Подробности и способ удаления без приложения — на <a href="/account-deletion">
отдельной странице</a>.</p>

<h2>Связь</h2>
<p>Вопросы о данных: <a href="mailto:zagirnur@gmail.com">zagirnur@gmail.com</a>.</p>
`,
	})
}

// handleAccountDeletion GET /account-deletion — как удалить аккаунт.
func (s *Server) handleAccountDeletion(w http.ResponseWriter, _ *http.Request) {
	writeLegal(w, legalData{
		Title:   "Удаление аккаунта",
		Updated: legalUpdated,
		Body: `
<h2>Из приложения</h2>
<p>Откройте «Профиль» → «Удалить аккаунт» и подтвердите. Аккаунт удаляется
сразу, повторный вход создаст новый.</p>

<h2>Без приложения</h2>
<p>Напишите на <a href="mailto:zagirnur@gmail.com">zagirnur@gmail.com</a> с
адреса или из аккаунта, которым вы входили. Мы удалим аккаунт в течение 30 дней
и ответим, когда это будет сделано.</p>

<h2>Что удаляется</h2>
<p>Профиль, способы входа, токены устройств для уведомлений, ваши черновики и
незавершённые сценарии.</p>

<h2>Что остаётся</h2>
<p>Расходы и погашения в общих группах: это общий счёт нескольких людей, и
удаление вашего аккаунта не должно менять их долги. Ваше имя в них заменяется на
«Удалённый пользователь».</p>
`,
	})
}

func writeLegal(w http.ResponseWriter, data legalData) {
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	// Страницы редко меняются, но и кешировать их надолго незачем: магазины
	// читают их вживую
	w.Header().Set("Cache-Control", "public, max-age=3600")
	_ = legalPage.Execute(w, data)
}
