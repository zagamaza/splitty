// Package safe — перехват паник в фоновой работе.
//
// Бот и REST живут в ОДНОМ процессе: паника в обработке одного телеграм-сообщения
// или в фоновой отправке уведомления уносит и второе. Одно неудачное сообщение
// не должно стоить всем остальным доступа к приложению.
package safe

import (
	"runtime/debug"

	"github.com/rs/zerolog/log"
)

// Recover перехватывает панику и пишет её в лог вместе со стеком.
// Вызывается через defer: defer safe.Recover("обработка обновления").
//
// Паника здесь — всегда дефект, и лог со стеком нужен, чтобы её нашли. Но
// уронить процесс она не должна: следующее сообщение обязано обработаться.
func Recover(what string) {
	if r := recover(); r != nil {
		log.Error().
			Str("where", what).
			Interface("panic", r).
			Str("stack", string(debug.Stack())).
			Msg("паника перехвачена")
	}
}

// Go запускает фоновую горутину с перехватом паники.
func Go(what string, fn func()) {
	go func() {
		defer Recover(what)
		fn()
	}()
}
