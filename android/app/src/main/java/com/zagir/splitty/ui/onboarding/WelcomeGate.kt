package com.zagir.splitty.ui.onboarding

/**
 * Когда показывать разовое приветствие.
 *
 * Приветствие идёт ДО входа, поэтому условий два, а не три:
 * — установка его ещё не видела (отметка по устройству, не по аккаунту: до
 *   входа аккаунта не существует, а сам вход означает «видел»);
 * — нет намерения вступить в тусу: человек пришёл по ссылке приглашения, и
 *   показать ему вместо тусы рассказ о продукте значит потерять переход.
 *
 * Числа групп здесь больше нет и быть не может: до входа групп не существует.
 *
 * Защёлки `alreadyHandled` тоже не осталось. Она гасила гонку «флаг читается с
 * диска, а запись туда асинхронна», и породил эту гонку DataStore; отметка
 * переехала в синхронный SharedPreferences (см. [SharedPrefsIntroSeen]), и окна
 * между «закрыл» и «записалось» не стало вовсе.
 *
 * Намерения по пушу в списке нет, и это не упущение. Пуш приходит только на
 * устройство, которое было вошедшим, а у такого отметка «видел» уже стоит:
 * либо перенесена миграцией, либо поставлена самим входом.
 */
fun shouldShowIntro(hasSeen: Boolean, hasPendingDeeplink: Boolean): Boolean {
    if (hasSeen) return false
    return !hasPendingDeeplink
}
