import XCTest
@testable import Splitty

/// Что обещает экран входа.
///
/// История здесь в две ступени. Сначала была одна строка «Делите расходы с
/// друзьями» — она описывает любое приложение категории и не отвечает ни на
/// один вопрос. Её сменили три пункта: что я записываю, что это даёт,
/// переводит ли приложение деньги.
///
/// Теперь пункт снова один, и это не откат. Приветствие переехало ПЕРЕД
/// входом, и первые два вопроса разбирают четыре страницы с арифметикой —
/// подробнее, чем строка списка. Повторять их на следующем экране значит
/// обещать одно и то же дважды.
///
/// А вот «оно спишет деньги?» приветствие не снимает, и снимать этот страх
/// надо ровно там, где человека просят войти.
final class LoginValuePropsTests: XCTestCase {

    func testSinglePropAfterIntroMoved() {
        XCTAssertEqual(
            LoginValueProp.all.count, 1,
            "экран входа снова дублирует то, что уже рассказало приветствие"
        )
    }

    func testEveryPropHasTitleAndDetail() {
        for prop in LoginValueProp.all {
            XCTAssertFalse(prop.title.isEmpty, "пункт \(prop.id) без заголовка")
            XCTAssertFalse(prop.detail.isEmpty, "пункт \(prop.id) без пояснения")
        }
    }

    /// Самый частый страх: «оно спишет деньги?». Ответ обязан быть на входе —
    /// его не даёт ни одна страница приветствия.
    func testMoneyDisclaimerIsPresent() {
        let money = LoginValueProp.all.first { $0.id == "money" }
        XCTAssertNotNil(money, "с экрана входа пропал пункт про то, что деньги передаёт человек сам")
    }
}
